function createAttachment(
  overrides: Partial<StorageAttachment> = {},
): StorageAttachment {
  return {
    id: 'attachment-1',
    uuid: 'attachment-uuid',
    name: 'documents',
    recordType: 'Template',
    recordId: 'template-1',
    blob: {
      id: 'blob-1',
      filename: 'contract.pdf',
      contentType: 'application/pdf',
      metadata: {},
      checksum: 'source-md5',
    } as StorageBlob,
    ...overrides,
  } as StorageAttachment;
}
