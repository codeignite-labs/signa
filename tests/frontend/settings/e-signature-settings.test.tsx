it("normalizes an empty owner role to First Party and avoids unchanged role saves", async () => {
  vi.mocked(auth.getAccountPreferences).mockResolvedValue({
    ...preferences,
    auto_sign_owner_enabled: true,
    auto_sign_owner_role: "Owner",
  });
  await renderSigningSettings();
  const input = screen.getByLabelText("Owner role name");
  fireEvent.blur(input);
  expect(auth.updateAccountPreferences).not.toHaveBeenCalled();
  fireEvent.change(input, { target: { value: "   " } });
  fireEvent.blur(input);
  await waitFor(() =>
    expect(auth.updateAccountPreferences).toHaveBeenCalledWith({
      auto_sign_owner_role: "First Party",
    }),
  );
  const blur = vi.spyOn(input, "blur");
  fireEvent.keyDown(input, { key: "Enter" });
  expect(blur).toHaveBeenCalledTimes(1);
});
