it.each(["activate", "remove", "upload"] as const)(
  "clears a removed TSA configuration when %s refreshes signing identities",
  async (action) => {
    await renderSigningSettings();
    vi.mocked(auth.listSigningCertificates).mockResolvedValue({
      data: [certificate],
      timestamp_server_url: null,
    });
    vi.mocked(auth.uploadSigningCertificate).mockResolvedValue(certificate);
    vi.mocked(auth.makeDefaultSigningCertificate).mockResolvedValue(
      certificate,
    );
    vi.mocked(auth.deleteSigningCertificate).mockResolvedValue(certificate);
    if (action === "upload") await submitCertificate("signing");
    else
      fireEvent.click(
        screen.getByRole("button", {
          name: `${action === "activate" ? "Activate" : "Remove"} ${certificate.name}`,
        }),
      );
    await waitFor(() =>
      expect(
        (screen.getByLabelText("Trusted timestamp service") as HTMLInputElement)
          .value,
      ).toBe(""),
    );
  },
);
